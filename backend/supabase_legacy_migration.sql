begin;

alter table public.brand_rules
    add column if not exists category text,
    add column if not exists title text,
    add column if not exists description text;

update public.brand_rules
set category = coalesce(category, rule_type, 'general'),
    title = coalesce(title, rule_name, 'Untitled rule'),
    description = coalesce(description, rule_description, '');

alter table public.brand_rules
    alter column category set not null,
    alter column title set not null,
    alter column description set not null;

create or replace function public.sync_brand_lens_rule_columns()
returns trigger
language plpgsql
as $$
begin
    if tg_op = 'INSERT' then
        new.category := coalesce(new.category, new.rule_type, 'general');
        new.title := coalesce(new.title, new.rule_name, 'Untitled rule');
        new.description := coalesce(new.description, new.rule_description, '');
        new.rule_type := coalesce(new.rule_type, new.category);
        new.rule_name := coalesce(new.rule_name, new.title);
        new.rule_description := coalesce(new.rule_description, new.description);
    else
        if new.category is distinct from old.category then
            new.rule_type := new.category;
        elsif new.rule_type is distinct from old.rule_type then
            new.category := new.rule_type;
        end if;

        if new.title is distinct from old.title then
            new.rule_name := new.title;
        elsif new.rule_name is distinct from old.rule_name then
            new.title := new.rule_name;
        end if;

        if new.description is distinct from old.description then
            new.rule_description := new.description;
        elsif new.rule_description is distinct from old.rule_description then
            new.description := new.rule_description;
        end if;
    end if;

    return new;
end;
$$;

drop trigger if exists sync_brand_lens_rule_columns on public.brand_rules;
create trigger sync_brand_lens_rule_columns
before insert or update on public.brand_rules
for each row execute function public.sync_brand_lens_rule_columns();

alter table public.submissions
    add column if not exists filename text not null default 'Legacy submission',
    add column if not exists employee_name text not null default 'Employee',
    add column if not exists content_text text,
    add column if not exists rules_snapshot jsonb not null default '[]'::jsonb,
    add column if not exists analysis_status text not null default 'completed',
    add column if not exists compliance_score integer,
    add column if not exists publishing_status text not null default 'Needs human review',
    add column if not exists violations jsonb not null default '[]'::jsonb,
    add column if not exists recommendations jsonb not null default '[]'::jsonb;

update public.submissions
set content_text = coalesce(content_text, content, ''),
    publishing_status = case lower(coalesce(status, ''))
        when 'approved' then 'Ready to publish'
        when 'rejected' then 'Changes required'
        else coalesce(publishing_status, 'Needs human review')
    end;

alter table public.submissions
    alter column content_text set not null;

create or replace function public.sync_brand_lens_submission_content()
returns trigger
language plpgsql
as $$
begin
    if tg_op = 'INSERT' then
        new.content_text := coalesce(new.content_text, new.content, '');
        new.content := coalesce(new.content, new.content_text);
    elsif new.content_text is distinct from old.content_text then
        new.content := new.content_text;
    elsif new.content is distinct from old.content then
        new.content_text := new.content;
    end if;

    return new;
end;
$$;

drop trigger if exists sync_brand_lens_submission_content on public.submissions;
create trigger sync_brand_lens_submission_content
before insert or update on public.submissions
for each row execute function public.sync_brand_lens_submission_content();

alter table public.tickets
    add column if not exists ticket_number bigint generated by default as identity,
    add column if not exists title text not null default 'Manual review',
    add column if not exists filename text not null default 'Legacy submission',
    add column if not exists priority text not null default 'Medium',
    add column if not exists note text not null default '';

update public.tickets
set note = coalesce(nullif(note, ''), message, '');

create unique index if not exists tickets_ticket_number_uidx
    on public.tickets (ticket_number);

create or replace function public.sync_brand_lens_ticket_message()
returns trigger
language plpgsql
as $$
begin
    if tg_op = 'INSERT' then
        new.note := coalesce(new.note, new.message, '');
        new.message := coalesce(new.message, new.note);
    elsif new.note is distinct from old.note then
        new.message := new.note;
    elsif new.message is distinct from old.message then
        new.note := new.message;
    end if;

    return new;
end;
$$;

drop trigger if exists sync_brand_lens_ticket_message on public.tickets;
create trigger sync_brand_lens_ticket_message
before insert or update on public.tickets
for each row execute function public.sync_brand_lens_ticket_message();

do $$
declare
    table_name text;
begin
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
        foreach table_name in array array['brand_rules', 'submissions', 'tickets']
        loop
            if not exists (
                select 1
                from pg_publication_tables
                where pubname = 'supabase_realtime'
                  and schemaname = 'public'
                  and tablename = table_name
            ) then
                execute format('alter publication supabase_realtime add table public.%I', table_name);
            end if;
        end loop;
    end if;
end;
$$;

notify pgrst, 'reload schema';

commit;
